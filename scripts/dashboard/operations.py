"""Background jobs and safe local actions. Never call Tk from these workers."""
from contextlib import contextmanager
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import sys
import threading
import traceback

import tracking as tr
from .data import DOCS, file_hash, find_git, fingerprint, load_settings, load_snapshot, read_json, timestamp


@contextmanager
def refresh_lock(root):
    directory = root / "reports"
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / "dashboard-refresh.lock").open("a+b") as handle:
        if handle.tell() == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        try:
            if sys.platform == "win32":
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise OSError("Another dashboard is refreshing this checkout. Wait for it to finish.") from exc
        try:
            yield
        finally:
            handle.seek(0)
            if sys.platform == "win32":
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle, fcntl.LOCK_UN)


GENERATED_DOCS = {"PROGRESS_TRACKER.md", "ROADMAP.md", "SESSION_HANDOFF.md", "audit/BACKLOG_RECONCILIATION.md"}


def save_provenance(root, started_at=None, before_reports=None, before_inputs=None):
    if before_inputs is not None and fingerprint(root, exclude=GENERATED_DOCS) != before_inputs:
        raise OSError("Project inputs changed while checks ran; refresh again before relying on freshness.")
    for name, filename in tr.REPORT_FILES.items():
        report = read_json(root / "reports" / filename)
        generated = timestamp(report.get("generated_at")) if isinstance(report, dict) else None
        if not generated or (started_at and generated.timestamp() < started_at.timestamp() - 2):
            raise OSError("A report was not generated by this refresh; freshness metadata was not replaced.")
        if before_reports is not None and file_hash(root / "reports" / filename) == before_reports.get(name):
            raise OSError("Report bytes did not change; this invocation cannot establish new freshness.")
    payload = {"schema_version": 1, "completed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "input_hash": fingerprint(root), "reports": {name: file_hash(root / "reports" / filename) for name, filename in tr.REPORT_FILES.items()}}
    tr.atomic_write(root / "reports/dashboard-refresh.json", json.dumps(payload, indent=2) + "\n")


def save_git_setting(root, value):
    value = value.strip()
    if value and (not Path(value).is_absolute() or not Path(value).is_file() or Path(value).name.casefold() not in {"git", "git.exe"}):
        raise ValueError("Select an existing absolute git.exe path, or leave blank for automatic discovery.")
    # Host-specific paths are intentionally stored only in ignored local reports.
    tr.atomic_write(root / "reports/dashboard-settings.json", json.dumps({"git_executable": value}, indent=2) + "\n")


def open_local(root, relative=None):
    root = Path(root).resolve()
    if relative not in (None, "reports", *DOCS, "scripts/DASHBOARD.md"):
        raise ValueError("Only known project documents and folders can be opened.")
    path = root if relative is None else tr.safe_path(root, relative)
    if not path.exists():
        raise FileNotFoundError(f"Unavailable: {relative or 'project folder'}")
    if sys.platform != "win32":
        raise OSError("Opening local files requires Windows.")
    os.startfile(str(path))


class BackgroundJobs:
    def __init__(self, root, emit):
        self.root, self.emit = Path(root).resolve(), emit
        self.guard = threading.Lock()
        self.thread = None

    @property
    def busy(self):
        return self.guard.locked()

    def start(self, refresh=False):
        if not self.guard.acquire(blocking=False):
            return False
        self.thread = threading.Thread(target=self._work, args=(refresh,), daemon=False)
        try:
            self.thread.start()
        except Exception:
            self.guard.release()
            raise
        return True

    def _work(self, refresh):
        code, error = None, None
        try:
            if refresh:
                from status_launcher import run_status
                with refresh_lock(self.root):
                    settings, issue = load_settings(self.root)
                    if issue:
                        self.emit(("output", issue + "\n"))
                    git = find_git(settings)
                    environment = dict(os.environ)
                    if git:
                        environment["PATH"] = str(Path(git).parent) + os.pathsep + environment.get("PATH", "")
                    def event(item):
                        nonlocal code, error
                        kind, value = item
                        if kind == "finished":
                            code = value
                        elif kind == "error":
                            error = value
                            self.emit(("output", value + "\n"))
                        else:
                            self.emit(item)
                    before_reports = {name: file_hash(self.root / "reports" / filename) for name, filename in tr.REPORT_FILES.items() if (self.root / "reports" / filename).is_file()}
                    before_inputs = fingerprint(self.root, exclude=GENERATED_DOCS)
                    started_at = datetime.now(timezone.utc)
                    run_status(self.root, event, environment=environment)
                    if code is not None:
                        # Bind snapshots after writes finish, including failed checks.
                        try:
                            save_provenance(self.root, started_at, before_reports, before_inputs)
                        except (OSError, ValueError) as exc:
                            self.emit(("output", f"Could not save report freshness metadata: {exc}\n"))
                    self.emit(("refresh_result", {"code": code, "error": error}))
            snapshot = load_snapshot(self.root)
            self.emit(("snapshot", snapshot))
        except Exception as exc:
            self.emit(("job_error", f"{'Refresh' if refresh else 'Data loading'} failed: {exc}\n{traceback.format_exc()}"))
        finally:
            self.guard.release()
            self.emit(("idle", refresh))
